import type { Core } from '@strapi/strapi';

const allowedMediaTypes = [
  'image/*',
  'video/*',
  'audio/*',
  'application/pdf',
  'application/msword',
  'application/vnd.openxmlformats-officedocument.*',
  'text/plain',
  'text/csv',
];

const deniedTypes = [
  'image/svg+xml',
  'application/vnd.microsoft.portable-executable',
  'application/x-msdownload',
  'application/x-msdos-program',
  'application/x-executable',
  'application/x-dosexec',
  'application/x-sh',
  'text/x-shellscript',
  'application/x-mach-binary',
];

const config = ({ env }: Core.Config.Shared.ConfigParams): Core.Config.Plugin => ({
  'users-permissions': {
    config: {
      jwtManagement: 'refresh',
      sessions: {
        httpOnly: true,
      },
    },
  },
  email: {
    config: {
      provider: 'nodemailer',
      providerOptions: {
        host: env('SMTP_HOST', 'localhost'),
        port: env.int('SMTP_PORT', 2525),
        // Port 465 uses implicit TLS; 587 and local sinks start in plain text.
        secure: env.int('SMTP_PORT', 2525) === 465,
        ...(env('SMTP_USERNAME')
          ? { auth: { user: env('SMTP_USERNAME'), pass: env('SMTP_PASSWORD') } }
          : {}),
      },
      settings: {
        defaultFrom: env('EMAIL_FROM', 'Redakcja <no-reply@redakcja.example>'),
        defaultReplyTo: env('EMAIL_REPLY_TO', 'redakcja@redakcja.example'),
      },
    },
  },
  upload: {
    config: {
      security: {
        allowedTypes: allowedMediaTypes,
        deniedTypes,
      },
    },
  },
});

export default config;
