"""Query transformations measured locally: rewrite, multi-query + RRF, HyDE, decomposition.

Retrieval is the real chapter-1 baseline (fixed 128/32 windows, multilingual-e5-small, Qdrant).
Only the query variants are human-written (`data/query_variants.jsonl`) instead of generated by a
model, so that the whole table runs without an API key. Read the chapter for what that means.

Run from the `code/` directory:  ../.venv/bin/python experiments/04_queries.py
"""
from __future__ import annotations

from collections import Counter

from ragbook.corpus import fixed_window_chunks, load_sections
from ragbook.embed import Embedder
from ragbook.evaluate import by_type, evaluate, load_golden
from ragbook.queries import ScriptedLLM, expand_query, load_variants, multi_retrieve
from ragbook.store import DenseIndex

WINDOW, OVERLAP = 128, 32
K, K_WIDE = 5, 20
COLUMNS = ["n", "recall@5", "recall@20", "mrr@5", "ndcg@5", "misses@5"]
LABELS = {"n": "Pytań", "recall@5": "recall@5", "recall@20": "recall@20",
          "mrr@5": "MRR@5", "ndcg@5": "nDCG@5", "misses@5": "Bez trafienia"}


def table(rows: list[dict]) -> str:
    head = "| Wariant | " + " | ".join(LABELS[c] for c in COLUMNS) + " |"
    lines = [head, "|---|" + "|".join("---" for _ in COLUMNS) + "|"]
    for r in rows:
        cells = [f"{r[c]:.2f}".replace(".", ",") if isinstance(r[c], float) else str(r[c]) for c in COLUMNS]
        lines.append(f"| {r['name']} | " + " | ".join(cells) + " |")
    return "\n".join(lines)


def main() -> None:
    sections = load_sections()
    golden = load_golden()
    variants = load_variants()
    by_question = {q.question: q.id for q in golden}

    embedder = Embedder()
    chunks = fixed_window_chunks(sections, embedder.tokenizer, window=WINDOW, overlap=OVERLAP)
    index = DenseIndex(embedder, chunks)
    llm = ScriptedLLM(variants)

    def scripted(question: str):
        return llm.for_question(by_question[question])

    def dense(text: str, k: int):
        return index.search(text, k)

    def dense_as_passage(text: str, k: int):
        """HyDE variant: embed the hypothetical answer with the `passage: ` prefix, like a document."""
        qv = embedder.embed_passages([text])[0]
        points = index.client.query_points(collection_name=index.collection,
                                           query=qv.tolist(), limit=k).points
        out = []
        for p in points:
            c = index.chunks[int(p.id)]
            out.append(type(c)(c.id, c.chapter, c.section, c.text, {**c.meta, "score": float(p.score)}))
        return out

    def variant_retriever(mode: str, search=dense, which: int | None = None):
        def retrieve(question: str, k: int):
            queries = expand_query(question, scripted(question), mode=mode)
            if which is not None:
                return search(queries[which], k)
            return search(queries[0], k) if len(queries) == 1 else multi_retrieve(search, queries, k)
        return retrieve

    runs = [
        ("baseline (pytanie użytkownika)", lambda q, k: dense(q, k)),
        ("rewrite 1", variant_retriever("multi", which=1)),
        ("rewrite 2", variant_retriever("multi", which=2)),
        ("multi-query (pytanie + 2 rewrite'y, RRF)", variant_retriever("multi")),
        ("HyDE (hipoteza jako query)", variant_retriever("hyde")),
        ("HyDE (hipoteza jako passage)", variant_retriever("hyde", search=dense_as_passage)),
        ("HyDE + pytanie (RRF)", variant_retriever("hyde+q")),
    ]

    results, rows = {}, []
    for name, retrieve in runs:
        res = evaluate(retrieve, golden, k=K, ks=(K, K_WIDE))
        results[name] = res
        rows.append({"name": name, **{c: res[c] for c in COLUMNS}})

    print("=== Techniki przekształcania zapytań, 49 pytań pozytywnych ===")
    print(table(rows))

    print("\n=== recall@5 po typach pytań ===")
    types = ("factual", "procedural", "comparative")
    sizes = Counter(row["type"] for row in results[runs[0][0]]["per_question"])
    print("| Wariant | " + " | ".join(f"{t} ({sizes[t]})" for t in types) + " |")
    print("|---|" + "|".join("---" for _ in types) + "|")
    for name, _ in runs:
        r5 = by_type(results[name], "recall@5")
        print(f"| {name} | " + " | ".join(f"{r5[t]:.2f}".replace(".", ",") for t in types) + " |")

    # Which of the nine chapter-1 misses does each technique repair?
    base = {row["id"]: row["recall@5"] for row in results[runs[0][0]]["per_question"]}
    misses = sorted(qid for qid, r in base.items() if r == 0)
    print(f"\n=== Pytania bez trafienia w baseline ({len(misses)}): {', '.join(misses)} ===")
    print("| Wariant | Naprawione | Zepsute | Netto |")
    print("|---|---|---|---|")
    for name, _ in runs[1:]:
        per = {row["id"]: row["recall@5"] for row in results[name]["per_question"]}
        fixed = sorted(qid for qid in misses if per[qid] > 0)
        broken = sorted(qid for qid, r in base.items() if r > 0 and per[qid] == 0)
        better = sum(1 for qid in base if per[qid] > base[qid])
        worse = sum(1 for qid in base if per[qid] < base[qid])
        print(f"| {name} | {', '.join(fixed) or '-'} | {', '.join(broken) or '-'} | "
              f"+{better} / -{worse} |")

    # Decomposition only makes sense on the comparative questions.
    comparative = [q for q in golden if q.type == "comparative"]
    print(f"\n=== Dekompozycja na pytaniach porównawczych ({len(comparative)}) ===")
    decomp_runs = [
        ("baseline", lambda q, k: dense(q, k)),
        ("multi-query (RRF)", variant_retriever("multi")),
        ("dekompozycja (2 podpytania, RRF)", variant_retriever("decompose")),
        ("dekompozycja + pytanie (RRF)", None),
    ]

    def decompose_plus_question(question: str, k: int):
        subs = expand_query(question, scripted(question), mode="decompose")
        return multi_retrieve(dense, [question, *subs], k)

    decomp_runs[-1] = (decomp_runs[-1][0], decompose_plus_question)
    drows = []
    for name, retrieve in decomp_runs:
        res = evaluate(retrieve, comparative, k=K, ks=(K, K_WIDE))
        drows.append({"name": name, **{c: res[c] for c in COLUMNS}})
        full = sum(1 for row in res["per_question"] if row["recall@5"] == 1.0)
        drows[-1]["full"] = full
    print(table(drows))
    print("Pytania z obiema trafnymi sekcjami w top-5: " +
          ", ".join(f"{r['name']}: {r['full']}/{len(comparative)}" for r in drows))

    # How much does a fused run cost in retrieval calls?
    print(f"\nWywołania retrievalu na pytanie: baseline 1, rewrite 1, multi-query 3, "
          f"HyDE 1, HyDE+pytanie 2, dekompozycja 2.")


if __name__ == "__main__":
    main()
